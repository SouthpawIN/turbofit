#!/usr/bin/env python3
"""Render normalized external benchmark evidence as a reviewable report."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any


ROOT = Path(__file__).resolve().parents[1]


def render(payload: dict[str, Any]) -> str:
    source = payload["source"]
    lines = [
        "# External benchmark intelligence",
        "",
        "External results are discovery evidence only. Turbofit promotes local runtime profiles only after reproducible local runs pass their gates.",
        "",
        f"- Source: [{source['name']}]({source['url']})",
        f"- Source generated: `{source['generated_at']}`",
        f"- Source tasks: `{source['task_count']}`",
        f"- Artifact identity: `{source['artifact_identity']}`",
        "",
        "| Model | Harness | Effort | pass@1 | pass@4 | Attempts | Median peak context | Turbofit candidate |",
        "|---|---|---:|---:|---:|---:|---:|---|",
    ]
    for row in sorted(payload["benchmarks"], key=lambda item: (-item["pass_at_1"], item["model"])):
        mapped = row.get("turbofit_model") or "-"
        context = row.get("median_peak_context_tokens")
        context_text = "-" if context is None else f"{int(context):,}"
        lines.append(
            f"| `{row['model']}` | `{row['harness']}` | `{row.get('reasoning_effort') or '-'}` | "
            f"{row['pass_at_1']:.3f} | {row['pass_at_4']:.3f} | {row['attempted']} | {context_text} | `{mapped}` |"
        )
    lines.extend(["", "Generated by `research/render_external_benchmarks.py`.", ""])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, default=ROOT / "research" / "external-benchmarks.json")
    parser.add_argument("--output", type=Path, default=ROOT / "references" / "external-benchmarks.md")
    args = parser.parse_args()
    payload = json.loads(args.input.read_text(encoding="utf-8"))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(render(payload), encoding="utf-8")
    print(args.output)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
